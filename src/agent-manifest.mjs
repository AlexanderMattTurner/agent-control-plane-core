/**
 * The per-agent manifest: every fact this package holds about how each agent's
 * hook transport behaves, published as plain JSON at
 * `schema/control-plane/v1/agents.json`.
 *
 * PROBLEM CLASS — a consumer that cannot call these adapters (a bash hook
 * wrapper, a Python validator, a monitor in another language) re-types each
 * agent's rules by hand: which exit code blocks, whether a block needs a
 * reason, whether an `ask` has a tier, which launcher option the adapter reads.
 * Each copy is one more place an agent's next release has to be chased into.
 * This file is the copy they read instead, generated from the live adapter
 * exports, so adding or changing an agent here changes what they read.
 *
 * Generated by `pnpm gen:schema`; `agent-manifest.test.mjs` regenerates it
 * in-process and byte-compares, so an adapter change landed without the regen
 * fails there.
 */

import { EventKind, blockTransportFor, lookup } from "./control-plane.mjs";
import { ADAPTERS, AGENT_IDS, LAUNCHER_OPTIONS } from "./registry.mjs";
import { HOST_FAILURE } from "./runtime.mjs";
import { SCHEMA_DIR } from "./json-schema.mjs";

/** Basename of the generated manifest, beside the schema documents. */
export const AGENT_MANIFEST_FILE = "agents.json";

/**
 * One agent's manifest row. Each field is copied from the adapter export it
 * names, never restated:
 * - `integration_mode`: the adapter's `INTEGRATION_MODE`.
 * - `native_ask_tier`: `NATIVE_ASK_TIER` — `false` means an `ask` the host
 *   receives does not stop the call, so a consumer must block instead.
 * - `block`: the `BLOCK_TRANSPORT` row — the exit code the host blocks on, the
 *   stream it reads the reason from, and whether an empty reason lets the call run.
 * - `host_failure`: the `HOST_FAILURE` row — how the host degrades a hook it
 *   cannot read (`blocks: false` with exit 0 means the call runs).
 * - `launcher_options`: the `LAUNCHER_OPTIONS` row — the options `adapterFor` reads.
 * - `coverage`: `COVERAGE`, per call class.
 * - `native_event_for`: `NATIVE_EVENT_FOR`, the native event name per kind.
 * - `unrendered_fields`: `UNRENDERED_FIELDS`, each set as a sorted list.
 * @param {string} id
 * @returns {Record<string, unknown>}
 */
function manifestRow(id) {
  const adapter = ADAPTERS[id];
  const failure = HOST_FAILURE[id];
  return {
    integration_mode: adapter.INTEGRATION_MODE,
    native_ask_tier: adapter.NATIVE_ASK_TIER,
    block: { ...blockTransportFor(id) },
    host_failure: { exit_code: failure.exit_code, blocks: failure.enforced },
    launcher_options: [...LAUNCHER_OPTIONS[id]],
    coverage: { ...adapter.COVERAGE },
    native_event_for: { ...adapter.NATIVE_EVENT_FOR },
    unrendered_fields: Object.fromEntries(
      Object.values(EventKind).map((kind) => {
        const fields = lookup(adapter.UNRENDERED_FIELDS, kind);
        // An empty list would publish "every field renders", the reverse of a
        // missing row's truth, so a gap refuses to generate.
        if (fields === undefined)
          throw new Error(
            `agent-manifest: ${id} has no UNRENDERED_FIELDS row for ${kind}`,
          );
        return [kind, [...fields].sort()];
      }),
    ),
  };
}

/**
 * The manifest, keyed by agent id in {@link AGENT_IDS} order.
 * @returns {Record<string, Record<string, unknown>>}
 */
export function agentManifest() {
  return Object.fromEntries(AGENT_IDS.map((id) => [id, manifestRow(id)]));
}

/**
 * The manifest keyed by its package-relative path, the shape the generator
 * writes and the freshness test reads.
 * @returns {Record<string, Record<string, unknown>>}
 */
export function agentManifestDocuments() {
  return { [`${SCHEMA_DIR}/${AGENT_MANIFEST_FILE}`]: agentManifest() };
}
